pub(crate) fn verify_key_attestation(
    certificate_chain_der: &[Vec<u8>],
    public_key_der: &[u8],
    client_nonce: &[u8],
    expected_app_certificate_digest: &str,
    unsafe_disable_device_safety_checks: bool,
) -> Result<AttestedDeviceInfo, ApiError> {
    let trust_anchors = trust_anchors();
    verify_key_attestation_with_roots(
        certificate_chain_der,
        public_key_der,
        client_nonce,
        trust_anchors.as_ref(),
        expected_app_certificate_digest,
        unsafe_disable_device_safety_checks,
    )
}

