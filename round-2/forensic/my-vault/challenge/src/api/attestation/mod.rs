fn verify_key_attestation_with_roots(
    certificate_chain_der: &[Vec<u8>],
    public_key_der: &[u8],
    client_nonce: &[u8],
    trust_anchors: &[TrustAnchor<'static>],
    expected_app_certificate_digest: &str,
    unsafe_disable_device_safety_checks: bool,
) -> Result<AttestedDeviceInfo, ApiError> {
    if certificate_chain_der.is_empty() {
        return Err(attestation_verification_error(
            "missing attestation certificate chain",
        ));
    }

    let leaf = parse_certificate(&certificate_chain_der[0])?;

    if leaf.public_key().raw != public_key_der {
        return Err(attestation_verification_error(
            "attestation leaf public key does not match request public key",
        ));
    }

    verify_certificate_chain(certificate_chain_der, trust_anchors)?;
    let key_description = parse_android_key_description(&leaf)?;

    if key_description.attestation_challenge != client_nonce {
        return Err(attestation_verification_error(
            "attestation challenge does not match client nonce",
        ));
    }
    if !key_description.purpose_decrypt {
        return Err(attestation_verification_error(
            "attested key is not authorized for decrypt purpose",
        ));
    }
    if !key_description.origin_generated {
        return Err(attestation_verification_error(
            "attested key origin is not generated",
        ));
    }
    if !unsafe_disable_device_safety_checks {
        verify_device_safety(&key_description)?;
    }

    let attested_device = key_description.attested_device_info();
    // AttestationApplicationId encodes package names and signing digests as sibling sets,
    // not package->digest pairs. Reject multi-package payloads so an expected digest
    // cannot be grafted onto the expected package name from another package entry.
    if !attested_device.has_unambiguous_package_identity(EXPECTED_ANDROID_PACKAGE_NAME) {
        return Err(attestation_verification_error(format!(
            "attestation application id does not uniquely identify expected package {EXPECTED_ANDROID_PACKAGE_NAME}",
        )));
    }
    if expected_app_certificate_digest != "*"
        && !attested_device.includes_application_signature_digest(expected_app_certificate_digest)
    {
        let present_signature_digests = attested_device
            .attestation_application_id
            .as_ref()
            .map(|application_id| application_id.signature_digests.as_slice())
            .unwrap_or_default();
        return Err(attestation_verification_error(format!(
            "attestation application id does not include expected signing certificate digest: expected={expected_app_certificate_digest}, present={present_signature_digests:?}",
        )));
    }

    Ok(attested_device)
}

fn verify_device_safety(key_description: &AndroidKeyDescription<'_>) -> Result<(), ApiError> {
    let root_of_trust = key_description
        .tee_authorizations
        .root_of_trust
        .as_ref()
        .ok_or_else(|| attestation_verification_error("missing attestation root of trust"))?;

    if !root_of_trust.device_locked {
        return Err(attestation_verification_error(
            "attestation device is not locked",
        ));
    }
    if root_of_trust.verified_boot_state != VERIFIED_BOOT_STATE_VERIFIED {
        return Err(attestation_verification_error(format!(
            "attestation verified boot state is not safe: {}",
            root_of_trust.verified_boot_state
        )));
    }
    if !has_non_zero_byte(root_of_trust.verified_boot_key) {
        return Err(attestation_verification_error(
            "attestation verified boot key is zero",
        ));
    }
    if !has_non_zero_byte(root_of_trust.verified_boot_hash) {
        return Err(attestation_verification_error(
            "attestation verified boot hash is zero",
        ));
    }

    Ok(())
}

fn has_non_zero_byte(bytes: &[u8]) -> bool {
    bytes.iter().any(|byte| *byte != 0)
}

fn parse_certificate(certificate_der: &[u8]) -> Result<X509Certificate<'_>, ApiError> {
    let (remaining, certificate) = X509Certificate::from_der(certificate_der).map_err(|error| {
        attestation_verification_error(format!("invalid attestation certificate DER: {error:?}"))
    })?;
    if !remaining.is_empty() {
        return Err(attestation_verification_error(
            "attestation certificate DER has trailing data",
        ));
    }
    Ok(certificate)
}

fn verify_certificate_chain(
    certificate_chain_der: &[Vec<u8>],
    trust_anchors: &[TrustAnchor<'static>],
) -> Result<(), ApiError> {
    if certificate_chain_der.len() < 2 {
        return Err(attestation_verification_error(
            "attestation certificate chain is missing root certificate",
        ));
    }

    let leaf_der = CertificateDer::from(certificate_chain_der[0].as_slice());
    let leaf = EndEntityCert::try_from(&leaf_der)
        .map_attestation_error("invalid attestation leaf certificate")?;
    let intermediate_certs = certificate_chain_der[1..certificate_chain_der.len() - 1]
        .iter()
        .map(|certificate_der| CertificateDer::from(certificate_der.as_slice()))
        .collect::<Vec<_>>();

    leaf.verify_for_usage(
        ALL_VERIFICATION_ALGS,
        trust_anchors,
        &intermediate_certs,
        UnixTime::now(),
        AndroidAttestationUsage,
        None,
        None,
    )
    .map_attestation_error("attestation certificate chain verification failed")?;

    Ok(())
}

struct AndroidAttestationUsage;

impl ExtendedKeyUsageValidator for AndroidAttestationUsage {
    fn validate(&self, iter: KeyPurposeIdIter<'_, '_>) -> Result<(), WebPkiError> {
        for key_purpose_id in iter {
            key_purpose_id?;
        }
        Ok(())
    }
}

trait AttestationResultExt<T> {
    fn map_attestation_error(self, reason: &'static str) -> Result<T, ApiError>;
}

impl<T, E: Debug> AttestationResultExt<T> for Result<T, E> {
    fn map_attestation_error(self, reason: &'static str) -> Result<T, ApiError> {
        self.map_err(|error| attestation_verification_error(format!("{reason}: {error:?}")))
    }
}

pub(super) fn attestation_verification_error(reason: impl Into<String>) -> ApiError {
    ApiError::untrusted_client_reason(format!(
        "key attestation verification failed: {}",
        reason.into()
    ))
}
